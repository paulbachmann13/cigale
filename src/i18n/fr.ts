/** Choisit la forme singulier/pluriel selon n (0 et 1 : singulier). */
export function plural(n: number, forms: { one: string; many: string }): string {
  return fmt(n > 1 ? forms.many : forms.one, { n });
}

/** Remplace {clé} par la valeur correspondante. */
export function fmt(text: string, vars: Record<string, string | number> = {}): string {
  return text.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));
}

